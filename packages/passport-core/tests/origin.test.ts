import { describe, expect, it } from 'vitest';
import { classifyClaimOrigin } from '../src/index';

const BRIEF = 'Мы делаем приложение для поиска попутчиков среди студентов. Провели две фокус-группы, 24 участника.';

describe('classifyClaimOrigin', () => {
  it('предложение из текста студента — его слова', () => {
    expect(classifyClaimOrigin('Провели две фокус-группы, 24 участника.', [BRIEF])).toBe('user');
  });

  it('те же слова в других падежах и порядке — всё равно слова студента', () => {
    expect(classifyClaimOrigin('Приложение ищет попутчиков для студентов', [BRIEF])).toBe('user');
  });

  it('новый смысл, которого студент не писал, — дописано ИИ', () => {
    expect(classifyClaimOrigin('Сервис монетизируется через подписку и партнёрские скидки', [BRIEF])).toBe('ai');
  });

  it('слова студента с добавкой модели: больше половины новых слов — дописано ИИ', () => {
    expect(classifyClaimOrigin('Приложение для студентов снижает транспортные расходы благодаря алгоритму подбора маршрутов', [BRIEF])).toBe('ai');
  });

  it('без текста студента всё дописано ИИ', () => {
    expect(classifyClaimOrigin('Сервис работает в нескольких городах', [])).toBe('ai');
  });

  it('утверждение без значимых слов остаётся за студентом', () => {
    expect(classifyClaimOrigin('— ', [BRIEF])).toBe('user');
  });

  it('числа сравниваются целиком', () => {
    expect(classifyClaimOrigin('Опрошено 240 человек', ['Опросили 24 человека'])).toBe('ai');
  });

  it('учитывает все переданные тексты студента', () => {
    expect(classifyClaimOrigin('Выручка составила 100 тысяч', [BRIEF, 'Выручка составила 100 тысяч рублей'])).toBe('user');
  });
});
